// Generates src/data/brandIcons.ts from the Simple Icons package (CC0).
// Only the icons referenced by the service catalog are copied, so the app
// ships a few kilobytes of SVG paths instead of the whole icon set.
// Usage: npm run icons
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const catalog = readFileSync(new URL('../src/data/catalog.ts', import.meta.url), 'utf8');
const slugs = [...new Set([...catalog.matchAll(/si: '([^']+)'/g)].map((m) => m[1]))].sort();

const out = {};
const missing = [];
for (const slug of slugs) {
  const file = new URL(`../node_modules/simple-icons/icons/${slug}.svg`, import.meta.url);
  if (!existsSync(file)) {
    missing.push(slug);
    continue;
  }
  const path = readFileSync(file, 'utf8').match(/<path d="([^"]+)"/)?.[1];
  if (path) out[slug] = path;
  else missing.push(slug);
}

const body = Object.entries(out)
  .map(([slug, d]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(d)},`)
  .join('\n');

writeFileSync(
  new URL('../src/data/brandIcons.ts', import.meta.url),
  `// Generated by scripts/build-brand-icons.mjs — do not edit by hand.
// Paths come from Simple Icons (https://simpleicons.org, CC0-1.0), drawn on a 24×24 grid.
// Brand names and logos are trademarks of their respective owners.
export const BRAND_ICONS: Record<string, string> = {
${body}
};
`,
);

console.log(`${Object.keys(out).length} icons written`);
if (missing.length) console.log(`No icon found for: ${missing.join(', ')} (a monogram is used instead)`);
